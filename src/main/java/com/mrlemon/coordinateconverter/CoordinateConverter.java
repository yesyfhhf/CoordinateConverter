    private void typeButtonActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_typeButtonActionPerformed
        if (isTypeON == true) {
            isTypeON = false;
            conversionLabel.setText("Overworld -> Nether");
            typeButton.setForeground(new java.awt.Color(217, 80, 80));
            convertButton.setForeground(new java.awt.Color(217, 80, 80));
            clearButton.setForeground(new java.awt.Color(217, 80, 80));
        }
        else if (isTypeON == false) {
            isTypeON = true;
            conversionLabel.setText("Overworld <- Nether");
            typeButton.setForeground(new java.awt.Color(124, 235, 124));
            convertButton.setForeground(new java.awt.Color(124, 235, 124));
            clearButton.setForeground(new java.awt.Color(124, 235, 124));
        }
    }//GEN-LAST:event_typeButtonActionPerformed

    private void convertButtonActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_convertButtonActionPerformed
       // true = OV - Nether
       // false = Nether - OV
    try {
       if (isTypeON == true) {
            xCoordString = xCoordText.getText();
            yCoordString = yCoordText.getText();
            
            if (xCoordText != null && yCoordText != null) {
                
                xCoord = Double.parseDouble(xCoordString);
                yCoord = Double.parseDouble(yCoordString);
                
                procCoordx = xCoord * 8;
                procCoordy = yCoord * 8;
                
              if (procCoordx >= 60000000 || procCoordy >= 60000000) {
                errorLabel.setText("Please enter a valid number.");
              } else {
                xCoordText.setText(Double.toString(procCoordx));
                yCoordText.setText(Double.toString(procCoordy));
              }
                
            } else {
                // this line is unreachable fyi
            }
       }
       else if (isTypeON == false) {
           xCoordString = xCoordText.getText();
           yCoordString = yCoordText.getText();
           
           if (xCoordText != null && yCoordText != null) {
                xCoord = Double.parseDouble(xCoordString);
                yCoord = Double.parseDouble(yCoordString);

                procCoordx = xCoord / 8;
                procCoordy = yCoord / 8;
                
              if (procCoordx >= 60000000 || procCoordy >= 60000000) {
                  errorLabel.setText("Please enter a valid number.");
              } else {
                xCoordText.setText(Double.toString(procCoordx));
                yCoordText.setText(Double.toString(procCoordy));
              }
               
           } else {
               // this line is unreachable fyi
           }
       }
        }
        catch (NumberFormatException e) {
           errorLabel.setText("One or more of your coordinate values is empty");
        }
    }//GEN-LAST:event_convertButtonActionPerformed

